// Word-analogy bank, grouped by relation type.
//
// Pair format: [a, b, difficulty = 1, notAllowed = []]
//   a : b          the related pair (direction matters).
//   difficulty     1 = everyday words, 2 = less common, 3 = hard.
//   notAllowed     words that must never be offered as a wrong answer when
//                  `a` is the question word, because a child could defend
//                  them as correct too (e.g. scissors also "cut").
//
// Group fields:
//   family     relations that feel alike share a family; the "pick the pair
//              with the same relation" format never uses a distractor pair
//              from the same family.
//   minLevel   lowest level that uses this group.
//   assoc      true when words linked to the question word through other
//              groups make safe "associated but wrong" distractors.
//   say(a, b)  short kid-language sentence describing the relation.
//
// Inside one group every `b` must be wrong for every other `a` (unless listed
// as the same `b`), so other pairs' answers are safe distractors.

