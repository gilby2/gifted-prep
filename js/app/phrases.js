const lastPicked = new Map();

// Random entry, never the same one twice in a row from the same list.
export function pick(list) {
  if (list.length < 2) return list[0];
  let i;
  do i = Math.floor(Math.random() * list.length);
  while (i === lastPicked.get(list));
  lastPicked.set(list, i);
  return list[i];
}

// Half ability praise, half effort praise. The two lists share no phrase, and
// each list avoids its own last pick, so the same praise never shows twice in a row.
export function pickPraise() {
  return pick(Math.random() < 0.5 ? PRAISE_ABILITY : PRAISE_EFFORT);
}
